"""Export the workbench's Pydantic contracts without adding a generation dependency."""

import argparse
from pathlib import Path

from presales.api.knowledge import (
    DecisionRequest,
    IndexRequest,
    KnowledgeUpload,
    ManifestRequest,
    MaterialUpload,
    ScopeRequest,
    SubmitRequest,
)
from presales.retrieval.models import Evidence, EvidenceQuery, RetrievalResult

MODELS = (
    EvidenceQuery,
    Evidence,
    RetrievalResult,
    KnowledgeUpload,
    MaterialUpload,
    IndexRequest,
    SubmitRequest,
    DecisionRequest,
    ManifestRequest,
    ScopeRequest,
)


def typescript(schema: dict) -> str:
    if "$ref" in schema:
        return schema["$ref"].rsplit("/", 1)[1]
    if "const" in schema:
        import json

        return json.dumps(schema["const"], ensure_ascii=False)
    if "enum" in schema:
        import json

        return " | ".join(json.dumps(v, ensure_ascii=False) for v in schema["enum"])
    if "anyOf" in schema:
        return " | ".join(typescript(v) for v in schema["anyOf"])
    kind = schema.get("type")
    if kind == "array":
        return f"Array<{typescript(schema.get('items', {}))}>"
    if kind == "object":
        required = schema.get("required", [])
        return (
            "{ "
            + "; ".join(
                f"{name}{'' if name in required else '?'}: {typescript(value)}"
                for name, value in schema.get("properties", {}).items()
            )
            + " }"
        )
    return {
        "integer": "number",
        "number": "number",
        "string": "string",
        "boolean": "boolean",
        "null": "null",
    }.get(kind, "unknown")


def generate() -> str:
    schemas = {}
    for model in MODELS:
        schema = model.model_json_schema()
        schemas.update(schema.pop("$defs", {}))
        schemas[model.__name__] = schema
    return (
        "// Generated by scripts/export_presales_dto.py; edit the Pydantic contracts.\n"
        + "\n".join(
            f"export type {name} = {typescript(schema)};"
            for name, schema in sorted(schemas.items())
        )
        + "\n"
    )


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    target = Path(__file__).resolve().parents[1] / "frontend/src/contracts.generated.ts"
    expected = generate()
    if args.check:
        if not target.is_file() or target.read_text(encoding="utf-8") != expected:
            parser.error("Generated DTO is stale")
    else:
        target.write_text(expected, encoding="utf-8")


if __name__ == "__main__":
    main()
